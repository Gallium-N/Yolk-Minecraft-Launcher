#!/usr/bin/env python3
"""Generate Theme.kt from the W3C DTCG color tokens in design/tokens.

Usage: python3 tools/gen_theme.py
Writes composeApp/src/commonMain/kotlin/dev/mayo/ymcl/ui/theme/Theme.kt.
"""
from __future__ import annotations

import json
import pathlib

ROOT = pathlib.Path(__file__).resolve().parent.parent
TOKENS = ROOT / "design" / "tokens"
OUT = ROOT / "composeApp" / "src" / "commonMain" / "kotlin" / "dev" / "mayo" / "ymcl" / "ui" / "theme" / "Theme.kt"

ROLE_ORDER = [
    "primary", "surfaceTint", "onPrimary", "primaryContainer", "onPrimaryContainer",
    "secondary", "onSecondary", "secondaryContainer", "onSecondaryContainer",
    "tertiary", "onTertiary", "tertiaryContainer", "onTertiaryContainer",
    "error", "onError", "errorContainer", "onErrorContainer",
    "background", "onBackground",
    "surface", "onSurface", "surfaceVariant", "onSurfaceVariant",
    "outline", "outlineVariant", "shadow", "scrim",
    "inverseSurface", "inverseOnSurface", "inversePrimary",
    "primaryFixed", "onPrimaryFixed", "primaryFixedDim", "onPrimaryFixedVariant",
    "secondaryFixed", "onSecondaryFixed", "secondaryFixedDim", "onSecondaryFixedVariant",
    "tertiaryFixed", "onTertiaryFixed", "tertiaryFixedDim", "onTertiaryFixedVariant",
    "surfaceDim", "surfaceBright",
    "surfaceContainerLowest", "surfaceContainerLow", "surfaceContainer",
    "surfaceContainerHigh", "surfaceContainerHighest",
]


def load(name: str) -> dict[str, str]:
    data = json.loads((TOKENS / name).read_text(encoding="utf-8"))["color"]
    colors: dict[str, str] = {}
    for role in ROLE_ORDER:
        if role not in data:
            raise SystemExit(f"missing token {role} in {name}")
        colors[role] = data[role]["$value"]
    if len(colors) != len(data):
        extra = set(data) - set(colors)
        raise SystemExit(f"unknown extra tokens in {name}: {sorted(extra)}")
    return colors


def kotlin_color(hex_value: str) -> str:
    value = hex_value.lstrip("#").upper()
    if len(value) == 6:
        value = "FF" + value
    if len(value) != 8:
        raise SystemExit(f"unsupported color {hex_value}")
    return "Color(0x%s)" % value


def scheme(name: str, colors: dict[str, str]) -> str:
    params = "\n".join(f"    {role} = {kotlin_color(value)}," for role, value in colors.items())
    return f"val {name}: ColorScheme = {name[0].lower() + name[1:]}(\n{params}\n)\n"


def main() -> None:
    dark = load("ymcl-dark.json")
    light = load("ymcl-light.json")

    header = '''// Generated by tools/gen_theme.py from design/tokens/*.json — do not edit by hand.
// 49 Material 3 roles per scheme, copied verbatim from the DTCG tokens.
package dev.mayo.ymcl.ui.theme

import androidx.compose.foundation.shape.RoundedCornerShape
import androidx.compose.material3.ColorScheme
import androidx.compose.material3.MaterialTheme
import androidx.compose.material3.Shapes
import androidx.compose.material3.Typography
import androidx.compose.material3.darkColorScheme
import androidx.compose.material3.lightColorScheme
import androidx.compose.runtime.Composable
import androidx.compose.ui.graphics.Color
import androidx.compose.ui.text.TextStyle
import androidx.compose.ui.text.font.FontWeight
import androidx.compose.ui.unit.dp
import androidx.compose.ui.unit.sp
import dev.mayo.ymcl.app.ThemeMode
import dev.mayo.ymcl.platform.isSystemDark

'''

    dark_scheme = "val YmclDarkColorScheme: ColorScheme = darkColorScheme(\n" + "\n".join(
        f"    {role} = {kotlin_color(value)}," for role, value in dark.items() if role != "shadow"
    ) + "\n)\n"
    light_scheme = "val YmclLightColorScheme: ColorScheme = lightColorScheme(\n" + "\n".join(
        f"    {role} = {kotlin_color(value)}," for role, value in light.items() if role != "shadow"
    ) + "\n)\n"
    # ColorScheme has no `shadow` role. Keep the two token values available so the
    # generated file still covers all 49 tokens.
    shadow_constants = (
        "// ColorScheme has no shadow role in this Material3 version; token kept for completeness.\n"
        f"val YmclShadowDark: Color = {kotlin_color(dark['shadow'])}\n"
        f"val YmclShadowLight: Color = {kotlin_color(light['shadow'])}\n"
    )

    tail = '''
val YmclTypography = Typography(
    displaySmall = TextStyle(fontSize = 36.sp, lineHeight = 44.sp, fontWeight = FontWeight.Bold),
    titleLarge = TextStyle(fontSize = 22.sp, lineHeight = 28.sp, fontWeight = FontWeight.SemiBold),
    titleMedium = TextStyle(fontSize = 16.sp, lineHeight = 24.sp, fontWeight = FontWeight.SemiBold),
    bodyMedium = TextStyle(fontSize = 14.sp, lineHeight = 20.sp),
    labelMedium = TextStyle(fontSize = 12.sp, lineHeight = 16.sp),
    labelSmall = TextStyle(fontSize = 11.sp, lineHeight = 16.sp),
)

val YmclShapes = Shapes(
    extraSmall = RoundedCornerShape(8.dp),
    small = RoundedCornerShape(12.dp),
    medium = RoundedCornerShape(16.dp),
    large = RoundedCornerShape(24.dp),
    extraLarge = RoundedCornerShape(24.dp),
)

@Composable
fun YmclTheme(
    themeMode: ThemeMode,
    content: @Composable () -> Unit,
) {
    val dark = when (themeMode) {
        ThemeMode.SYSTEM -> isSystemDark()
        ThemeMode.LIGHT -> false
        ThemeMode.DARK -> true
    }
    MaterialTheme(
        colorScheme = if (dark) YmclDarkColorScheme else YmclLightColorScheme,
        typography = YmclTypography,
        shapes = YmclShapes,
        content = content,
    )
}
'''

    OUT.parent.mkdir(parents=True, exist_ok=True)
    OUT.write_text(header + dark_scheme + "\n" + shadow_constants + "\n" + light_scheme + tail, encoding="utf-8", newline="\n")
    print(f"wrote {OUT.relative_to(ROOT)} ({len(dark)} dark + {len(light)} light roles)")


if __name__ == "__main__":
    main()

